// Writes firmware/test/test_pq/pq_vectors.h from the TypeScript reference (shared/src/pq.ts).
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { keccak256, toUtf8Bytes } from "ethers";
import { PqKeyTree, encodePqSignature } from "../src/pq";

const seed = keccak256(toUtf8Bytes("hisn pq test vector seed"));
const ctx = { chainId: 296, vault: "0x00000000000000000000000000000000004E5a1d" };
const height = 4;
const tree = new PqKeyTree(seed, height);
const cases = [0, 5, 15].map((leaf) => {
  const digest = keccak256(toUtf8Bytes(`digest ${leaf}`));
  return { leaf, digest, encoded: encodePqSignature(tree.sign(ctx, digest, leaf)) };
});
const q = (s: string | number) => JSON.stringify(String(s));
const out = `#pragma once
// Generated by shared/scripts/gen-pq-vectors.ts. Do not edit.
#define PQV_SEED ${q(seed)}
#define PQV_VAULT ${q(ctx.vault)}
#define PQV_CHAIN_ID ${ctx.chainId}ULL
#define PQV_HEIGHT ${height}
#define PQV_ROOT ${q(tree.root)}
typedef struct { unsigned leaf; const char *digest; const char *encoded; } pq_vector;
static const pq_vector PQV_CASES[] = {
${cases.map((c) => `  {${c.leaf}, ${q(c.digest)}, ${q(c.encoded)}},`).join("\n")}
};
`;
writeFileSync(resolve(__dirname, "../../firmware/test/test_pq/pq_vectors.h"), out);
console.log("root", tree.root);
