// Copies the shared library and the dashboard's data layer into src/core, so the app builds on its own
// (EAS installs only mobile/). Run after changing shared/ or dashboard/src/data|lib: npm run sync-core
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "..", "..");
const out = resolve(here, "..", "src", "core");
rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, "shared"), { recursive: true });
mkdirSync(join(out, "data"), { recursive: true });
mkdirSync(join(out, "lib"), { recursive: true });

const banner = (from) => `// Generated by scripts/sync-core.mjs from ${from}. Do not edit here.\n`;

function copy(from, to, rewrite) {
  let s = readFileSync(join(repo, from), "utf8");
  s = rewrite ? rewrite(s) : s;
  writeFileSync(join(out, to), banner(from) + s);
}

for (const f of readdirSync(join(repo, "shared", "src"))) {
  if (f.endsWith(".ts")) copy(`shared/src/${f}`, `shared/${f}`);
}

const toShared = (depth) => (s) => s.replaceAll('from "@hisn/shared"', `from "${depth}shared"`);
for (const f of ["mock.ts", "types.ts", "live.ts"]) copy(`dashboard/src/data/${f}`, `data/${f}`, toShared("../"));
for (const f of ["format.ts", "phase.ts", "windows.ts", "agentRules.ts"]) copy(`dashboard/src/lib/${f}`, `lib/${f}`, toShared("../"));

// people.ts keeps names in localStorage on the web; the app keeps them in memory.
copy("dashboard/src/lib/people.ts", "lib/people.ts", (s) =>
  toShared("../")(s)
    .replace(/JSON\.parse\(localStorage\.getItem\(KEY\) \?\? "\{\}"\)/, "JSON.parse(\"{}\")")
    .replace(/\s*localStorage\.setItem\(KEY, JSON\.stringify\(next\)\);/, ""),
);
console.log(`synced into ${out}`);
